CREATE OR REPLACE TABLE UDAY_STUDENT_PERFORMANCE AS

SELECT
    SEQ4() + 1 AS RECORD_ID,

    UNIFORM(1000, 9999, RANDOM()) AS STUDENT_ID,

    GET(
        ARRAY_CONSTRUCT(
            'UDAY',
            'RAHUL',
            'ANANYA',
            'SNEHA',
            'ARJUN',
            'PRIYA',
            'KARTHIK',
            'MEGHANA',
            'VARUN',
            'DIVYA'
        ),
        UNIFORM(0, 10, RANDOM())
    )::VARCHAR AS STUDENT_NAME,

    GET(
        ARRAY_CONSTRUCT(
            'CSE',
            'ECE',
            'IT',
            'AIML',
            'MECHANICAL'
        ),
        UNIFORM(0, 5, RANDOM())
    )::VARCHAR AS DEPARTMENT,

    GET(
        ARRAY_CONSTRUCT(
            'HYDERABAD',
            'KHAMMAM',
            'WARANGAL',
            'VIJAYAWADA',
            'CHENNAI'
        ),
        UNIFORM(0, 5, RANDOM())
    )::VARCHAR AS CITY,

    UNIFORM(18, 26, RANDOM()) AS AGE,

    ROUND(UNIFORM(600, 1000, RANDOM()) / 100.0, 2) AS CGPA,

    UNIFORM(3000, 15000, RANDOM()) AS COURSE_FEE,

    DATEADD(
        DAY,
        UNIFORM(0, 1095, RANDOM()),
        '2023-01-01'::DATE
    ) AS ENROLLMENT_DATE,

    GET(
        ARRAY_CONSTRUCT(
            'ENROLLED',
            'COMPLETED',
            'PENDING',
            'CANCELLED'
        ),
        UNIFORM(0, 4, RANDOM())
    )::VARCHAR AS ENROLLMENT_STATUS

FROM TABLE(GENERATOR(ROWCOUNT => 10000));   


