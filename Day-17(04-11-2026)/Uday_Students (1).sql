SELECT
    STUDENT_ID,
    STUDENT_NAME,
    AGE,
    DEPARTMENT,
    CGPA,
    CITY
FROM UDAY_STUDENTS_RAW_TABLE
WHERE
    NULLIF(TRIM(STUDENT_NAME), '') IS NULL
    OR NULLIF(TRIM(AGE), '') IS NULL
    OR NULLIF(TRIM(DEPARTMENT), '') IS NULL
    OR NULLIF(TRIM(CGPA), '') IS NULL
    OR NULLIF(TRIM(CITY), '') IS NULL;


CREATE OR REPLACE TABLE UDAY_STUDENTS AS
SELECT
    TRY_TO_NUMBER(TRIM(STUDENT_ID)) AS STUDENT_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(STUDENT_NAME)), ''),
        'UNKNOWN'
    ) AS STUDENT_NAME,

    TRY_TO_NUMBER(NULLIF(TRIM(AGE), '')) AS AGE,

    COALESCE(
        NULLIF(UPPER(TRIM(DEPARTMENT)), ''),
        'UNKNOWN'
    ) AS DEPARTMENT,

    TRY_TO_DECIMAL(
        NULLIF(TRIM(CGPA), ''),
        3, 2
    ) AS CGPA,

    COALESCE(
        NULLIF(UPPER(TRIM(CITY)), ''),
        'UNKNOWN'
    ) AS CITY

FROM UDAY_STUDENTS_RAW_TABLE;


CREATE OR REPLACE TABLE UDAY_ENROLLMENTS AS
SELECT
    TRY_TO_NUMBER(TRIM(ENROLLMENT_ID)) AS ENROLLMENT_ID,

    TRY_TO_NUMBER(TRIM(STUDENT_ID)) AS STUDENT_ID,

    TRY_TO_NUMBER(TRIM(COURSE_ID)) AS COURSE_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(ENROLLMENT_STATUS)), ''),
        'UNKNOWN'
    ) AS ENROLLMENT_STATUS

FROM UDAY_ENROLLMENTS_RAW_TABLE;



CREATE OR REPLACE TABLE UDAY_COURSES AS
SELECT
    TRY_TO_NUMBER(TRIM(COURSE_ID)) AS COURSE_ID,

    COALESCE(
        NULLIF(UPPER(TRIM(COURSE_NAME)), ''),
        'UNKNOWN'
    ) AS COURSE_NAME,

    COALESCE(
        NULLIF(UPPER(TRIM(CATEGORY)), ''),
        'UNKNOWN'
    ) AS CATEGORY,

    COALESCE(NULLIF(TRIM(COURSE_FEE), ''),'UNKNOWN') AS COURSE_FEE

FROM UDAY_COURSES_RAW_TABLE;


